// writeObservabilityTable renders the observability CAPABILITY comparison (not a
// pass/fail gate). Two axes: the framework's native observability platform
// (documented) and the arena-measured in-process OTel emission + span_count +
// logs_structured.
func writeObservabilityTable(b *strings.Builder, rep reportData) {
	if len(rep.ObsRecords) == 0 {
		return
	}
	b.WriteString("## Observability — capability comparison (not a pass/fail gate)\n\n")
	b.WriteString("Two axes. **Native platform** is each framework's own observability suite\n")
	b.WriteString("(documented, not measured here). **In-process OTel (arena-measured)** is what the\n")
	b.WriteString("`observability` mode actually emitted when driven through a real multi-op turn with\n")
	b.WriteString("an in-memory OpenTelemetry span exporter: whether OTel spans were produced, the\n")
	b.WriteString("**span count**, and whether logs were **structured**. The arena reading is a\n")
	b.WriteString("deliberately **narrow lens** — it measures in-process span emission with an in-memory\n")
	b.WriteString("exporter and does **not** capture a framework's full native platform.\n\n")
	b.WriteString("| Framework | Native platform | In-proc OTel emission | OTel measured | Spans | Structured logs | Span names |\n")
	b.WriteString("|---|---|---|:--:|--:|:--:|---|\n")
	for _, fw := range rep.Frameworks {
		r, ok := obsByFramework(rep.ObsRecords, fw)
		if !ok {
			continue
		}
		plat := nativeObsPlatform[fw]
		measured := sigUnknown
		spans := sigUnknown
		logs := sigUnknown
		names := sigUnknown
		if r.Measured {
			if r.OtelSupported {
				measured = "native " + sigPass
			} else {
				measured = "no spans " + sigFail
			}
			spans = fmt.Sprintf("%d", r.SpanCount)
			logs = boolGlyph(r.LogsStructured)
			names = spanNamesCell(r.SpanNames)
		} else if r.Note != "" {
			measured = tail(r.Note, 40)
		} else if r.RanErr != "" {
			measured = "run error"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s |\n",
			fw, plat.Platform, plat.Emission, measured, spans, logs, names)
	}
	b.WriteString("\n")
}

func boolGlyph(v bool) string {
	if v {
		return sigPass
	}
	return sigFail
}

