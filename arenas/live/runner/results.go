// reportData is everything writeResults needs to render RESULTS.md.
type reportData struct {
	Model       string
	Frameworks  []string
	Modes       []string
	Dimensions  []string
	BenchModes  []string
	Forms       []string
	BenchIters  int
	ColdProbes  int
	JudgeOn     bool
	Concurrency int      // -concurrency the correctness/quality pass ran under (1 = sequential)
	RPS         float64  // -rps client-side global model-call pacing (0 = off)
	Lane        string   // "real" | "stub" — which model lane this run scored (ARENA_STUB)
	LaneLeaks   []string // frameworks that reported the REAL model during a STUB run (should be empty)
	Records     []record
	Benches     []benchCell
	IsoRecords  []isoRecord
	CrashRecs   []crashRecord
	ObsRecords  []obsRecord
	MatrixDocs  []matrixDoc
	ModelCalls  int
}

// per (framework, mode) correctness aggregate.
type modeAgg struct {
	runs, errors int

	// PRIMARY: the deterministic score (arenas/live/runner/scoring), always
	// computed — no LLM, no network, no randomness.
	detN      int     // records with a deterministic score computed
	detPassN  int     // of those, how many Pass
	detValSum float64 // sum of Score.Value, for an average

	// SECONDARY, opt-in (-llm-judge): agnes-as-judge scores.
	corrSum, helpSum, faithSum, judged int

	latSum int64
	latN   int
	inSum  int
	outSum int
	tokN   int

	// rag
	groundedN, retrievalHits int
	trapN, trapRefused       int

	// tools
	toolN, toolExec, toolCorrect int

	// structured
	structN, structOK int

	// stream
	ttftSum int64
	ttftN   int
}

func writeResults(path string, rep reportData) error {
	// aggregate correctness records per (framework, mode)
	aggs := map[string]*modeAgg{}
	key := func(fw, mode string) string { return fw + "\x00" + mode }
	get := func(fw, mode string) *modeAgg {
		k := key(fw, mode)
		a := aggs[k]
		if a == nil {
			a = &modeAgg{}
			aggs[k] = a
		}
		return a
	}
	for _, r := range rep.Records {
		a := get(r.Framework, r.Mode)
		a.runs++
		if r.failed() {
			a.errors++
			continue
		}
		a.latSum += r.WallMs
		a.latN++
		if r.HasTok {
			a.inSum += r.SumIn
			a.outSum += r.SumOut
			a.tokN++
		}
		a.detN++
		a.detValSum += r.Det.Value
		if r.Det.Pass {
			a.detPassN++
		}
		if r.Correctness > 0 {
			a.corrSum += r.Correctness
			a.helpSum += r.Helpfulness
			a.faithSum += r.Faithfulness
			a.judged++
		}
		switch r.Kind {
		case "rag_grounded":
			a.groundedN++
			if r.RetrievalHit {
				a.retrievalHits++
			}
		case "rag_trap":
			a.trapN++
			if r.TrapRefused {
				a.trapRefused++
			}
		case "tools":
			a.toolN++
			if r.ToolExecuted {
				a.toolExec++
			}
			if r.AnswerCorrect {
				a.toolCorrect++
			}
		case "structured":
			a.structN++
			if r.StructuredOK {
				a.structOK++
			}
		case "stream":
			if r.TTFTMs > 0 {
				a.ttftSum += r.TTFTMs
				a.ttftN++
			}
		}
	}

	var b strings.Builder
	writeHeader(&b, rep)
	writeMatrixSection(&b, rep)
	writeQualityTable(&b, rep, aggs, get)
	writeJudgeSection(&b, rep, get)
	writeScopedIsolationTable(&b, rep)
	writeCrashTable(&b, rep)
	writeObservabilityTable(&b, rep)
	writeBenchmarks(&b, rep)
	writeTokenTable(&b, rep, aggs, get)
	writeFrameworkOverheadTable(&b, rep, aggs, get)
	writePerItemDetail(&b, rep.Records)
	writeNotes(&b, rep)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

