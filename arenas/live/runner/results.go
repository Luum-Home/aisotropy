// writeQualityTable renders the PRIMARY, deterministic correctness/quality
// table (arenas/live/runner/scoring) — always computed, no LLM/network/
// randomness. See docs/architecture/arena-deterministic-judging.md.
func writeQualityTable(b *strings.Builder, rep reportData, aggs map[string]*modeAgg, get func(fw, mode string) *modeAgg) {
	b.WriteString("## Correctness / quality — per framework × per mode (PRIMARY, deterministic)\n\n")
	b.WriteString("**Deterministic score** is `pass/total` from `arenas/live/runner/scoring` — pure,\n")
	b.WriteString("reproducible, mode-specific correctness (see the primary-score note above). The **Mode\n")
	b.WriteString("signal** column restates the same underlying measurement in mode-specific units (rag:\n")
	b.WriteString("retrieval hit@1 on the gold doc + trap-refusal; tools: real tool execution + numeric\n")
	b.WriteString("correctness; structured: schema-valid JSON; stream: mean TTFT). Latency is end-to-end\n")
	b.WriteString("wall-clock (native, correctness pass) including the real model round-trip(s).\n\n")

	writeRunSummary(b, rep.Records)

	if rep.Concurrency > 1 {
		fmt.Fprintf(b, "_Ran under `-concurrency %d`: up to %d frameworks' correctness/quality sweeps executed\n", rep.Concurrency, rep.Concurrency)
		b.WriteString("concurrently, so per-item latency in this pass reflects mild host contention — a\n")
		b.WriteString("directional signal, not a clean isolated p50. The benchmark pass below always stays\n")
		b.WriteString("sequential/uncontended and remains the p50/p95 source of truth for latency._\n\n")
		if rep.RPS > 0 {
			fmt.Fprintf(b, "_Model calls were paced client-side at `-rps %.3g/s` (global across all frameworks)\n", rep.RPS)
			b.WriteString("to stay under the shared agnes free-tier rate limit — see docs/architecture/arena-rate-limiting.md._\n\n")
		}
	} else {
		b.WriteString("_Ran under `-concurrency 1` (fully sequential) — latency in this pass is uncontended._\n\n")
	}
	b.WriteString("| Framework | Mode | Deterministic score | Avg value | Mode signal | Avg latency (ms) | Runs | Err |\n")
	b.WriteString("|---|---|---:|---:|---|---:|---:|---:|\n")

	for _, fw := range rep.Frameworks {
		for _, mode := range rep.Modes {
			a := get(fw, mode)
			if a.runs == 0 {
				continue
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %d | %d |\n",
				fw, mode,
				detScoreCell(a),
				fmt1(avg2(a.detValSum, a.detN)),
				modeSignal(mode, a),
				fmtLatency(a.latSum, a.latN),
				a.runs, a.errors,
			)
		}
	}
	b.WriteString("\n")

	writeQualityLegend(b)
}

// writeRunSummary renders the run-level aggregate (total / scored / errored)
// near the TOP of the correctness section, before the 48-row table, so a
// reader sees the scale of exclusion before reading individual cells. See
// writeQualityLegend for the per-cell denominator explanation, and record's
// failed() for what "errored" means (adapter crash / timeout / bad JSON /
// retry exhaustion — an infrastructure signal, not a framework-quality one).
func writeRunSummary(b *strings.Builder, records []record) {
	total := len(records)
	errored := 0
	for _, r := range records {
		if r.failed() {
			errored++
		}
	}
	scored := total - errored
	fmt.Fprintf(b, "**Run summary (this pass):** %d total runs — %d scored, %d errored", total, scored, errored)
	if total > 0 && errored > 0 {
		fmt.Fprintf(b, " (%.1f%% of runs never produced a scoreable answer)", 100*float64(errored)/float64(total))
	}
	b.WriteString(".\n\n")
}

// writeQualityLegend explains the score cell's denominator and the meaning of
// a trailing "(N err)" marker — see the honesty-defect fix this closes:
// errored runs (adapter crash / timeout / retry exhaustion) were previously
// silently dropped from the denominator, so e.g. "3/3 ✓" could mean 3 of 6
// invocations never ran. The error count now renders INSIDE the score cell,
// not only in the far-right "Err" column, so it cannot be missed at a glance.
func writeQualityLegend(b *strings.Builder) {
	b.WriteString("> **Denominator legend.** `pass/total` in the Deterministic score column counts only\n")
	b.WriteString("> **scored** runs — invocations that completed and were graded by\n")
	b.WriteString("> `arenas/live/runner/scoring`. A trailing `(N err)` marks runs that were EXCLUDED\n")
	b.WriteString("> from that denominator because they never produced a scoreable answer (adapter\n")
	b.WriteString("> crash, provider timeout, or retry exhaustion — see the `Runs`/`Err` columns for the\n")
	b.WriteString("> raw counts). An errored run is an **infrastructure** signal, not a framework-quality\n")
	b.WriteString("> one — it is never counted as a scoring failure and never silently dropped either.\n")
	b.WriteString("> Read `3/3 ✓ (3 err)` as: \"the 3 runs that completed all scored a perfect pass; 3\n")
	b.WriteString("> more runs of this cell never got that far.\" A `✓`/`✗` glyph always reflects only the\n")
	b.WriteString("> scored subset — check the `(N err)` marker before reading a `✓` as full coverage.\n\n")
}

// detScoreCell renders the primary deterministic pass/total cell, e.g. "4/5 ✓",
// with a trailing "(N err)" when this (framework, mode) cell also had runs
// that never reached scoring (see writeQualityLegend). The error count is
// rendered INSIDE the score cell — not only in the table's far-right "Err"
// column — so a reader cannot mistake a perfect score for full coverage.
func detScoreCell(a *modeAgg) string {
	base := sigUnknown
	if a.detN > 0 {
		glyph := sigFail
		if a.detPassN == a.detN {
			glyph = sigPass
		}
		base = fmt.Sprintf("%d/%d %s", a.detPassN, a.detN, glyph)
	}
	if a.errors > 0 {
		return fmt.Sprintf("%s (%d err)", base, a.errors)
	}
	return base
}

// writeJudgeSection renders the SECONDARY, opt-in LLM-as-judge table. Only
// emitted when the judge actually ran this run (-llm-judge); otherwise a
// one-line note explains it is off by default, so the report never silently
// omits an explanation for a blank section.
func writeJudgeSection(b *strings.Builder, rep reportData, get func(fw, mode string) *modeAgg) {
	b.WriteString("## LLM-as-judge — SECONDARY, opt-in (`-llm-judge`)\n\n")
	if !rep.JudgeOn {
		b.WriteString("_Skipped this run (default: off). Pass `-llm-judge` to enable — see the self-judge\n")
		b.WriteString("caveat above. The primary deterministic table above is unaffected either way._\n\n")
		return
	}
	b.WriteString("Quality axes are 1–5 (LLM-judged, higher is better), averaged over the judged tasks of\n")
	b.WriteString("that mode. **Treat as a relative, directional signal — not ground truth** (see the\n")
	b.WriteString("self-judge caveat above); the primary score is the deterministic table above.\n\n")
	b.WriteString("| Framework | Mode | Correctness | Helpfulness | Faithfulness | Judged runs |\n")
	b.WriteString("|---|---|---:|---:|---:|---:|\n")
	for _, fw := range rep.Frameworks {
		for _, mode := range rep.Modes {
			a := get(fw, mode)
			if a.judged == 0 {
				continue
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %d |\n",
				fw, mode,
				fmt1(avg(a.corrSum, a.judged)),
				fmt1(avg(a.helpSum, a.judged)),
				fmt1(avg(a.faithSum, a.judged)),
				a.judged,
			)
		}
	}
	b.WriteString("\n")
}

func modeSignal(mode string, a *modeAgg) string {
	switch mode {
	case "rag":
		parts := []string{}
		if a.groundedN > 0 {
			parts = append(parts, fmt.Sprintf("hit@1 %d/%d", a.retrievalHits, a.groundedN))
		}
		if a.trapN > 0 {
			parts = append(parts, fmt.Sprintf("trap-refuse %d/%d", a.trapRefused, a.trapN))
		}
		if len(parts) == 0 {
			return "—"
		}
		return strings.Join(parts, ", ")
	case "tools":
		if a.toolN == 0 {
			return "—"
		}
		return fmt.Sprintf("exec %d/%d, correct %d/%d", a.toolExec, a.toolN, a.toolCorrect, a.toolN)
	case "structured":
		if a.structN == 0 {
			return "—"
		}
		return fmt.Sprintf("valid %d/%d", a.structOK, a.structN)
	case "stream":
		if a.ttftN == 0 {
			return "—"
		}
		return fmt.Sprintf("TTFT %dms (n=%d)", a.ttftSum/int64(a.ttftN), a.ttftN)
	case "memory":
		return "recall (judged)"
	default:
		return "—"
	}
}

// writeScopedIsolationTable renders the multi-tenant scoped-memory & isolation
// dimension: per framework, same-scope hit / cross-tenant miss / leak-detected,
// sourced from each adapter's authoritative test-isolation.sh.
func writeScopedIsolationTable(b *strings.Builder, rep reportData) {
	if len(rep.IsoRecords) == 0 {
		return
	}
	b.WriteString("## Scoped memory & tenant isolation — `memory_scoped` + `isolation_leak`\n\n")
	b.WriteString("Multi-tenant scoped memory: a fact written under a compound scope\n")
	b.WriteString("`(tenant_id, user_id, product_id)` must be recalled in that exact scope\n")
	b.WriteString("(**same-scope hit**), must NOT be recalled under a different `tenant_id`\n")
	b.WriteString("(**cross-tenant miss**), and a secret seeded by tenant A must never surface when\n")
	b.WriteString("probed as tenant B (**leak? = none**). `memory_scoped` PASSes iff same-scope hit\n")
	b.WriteString("**and** cross-tenant miss; `isolation_leak` PASSes iff no leak. Each row is sourced\n")
	b.WriteString("from that adapter's own `test-isolation.sh` (real agnes recall/probe calls), the\n")
	b.WriteString("authoritative deterministic signal for its specific contract.\n\n")
	b.WriteString("> **Native vs hand-rolled (honest caveat).** aisotropy enforces tenant isolation\n")
	b.WriteString("> **by construction** in the core runtime — `tenant_id` travels only via\n")
	b.WriteString("> `context.Context` and Qdrant does payload-filtered HNSW scans (a constitutional\n")
	b.WriteString("> gate), so it ships **no** hand-rolled arena isolation harness. Every other\n")
	b.WriteString("> framework here has **no native multi-tenant memory primitive** and hand-rolls a\n")
	b.WriteString("> compound scope key over its store; this table exercises exactly that hand-rolled\n")
	b.WriteString("> key. A blank aisotropy row is therefore *by design*, not a failure.\n\n")
	b.WriteString("| Framework | Same-scope hit | Cross-tenant miss | `memory_scoped` | Leak? (none=pass) | Suite (test-isolation.sh) |\n")
	b.WriteString("|---|:--:|:--:|:--:|:--:|---|\n")
	for _, fw := range rep.Frameworks {
		r, ok := isoByFramework(rep.IsoRecords, fw)
		if !ok {
			continue
		}
		suite := isoSuiteCell(r)
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s |\n",
			fw, r.SameScopeHit, r.CrossTenantMiss, r.scopedPass(), leakCell(r.LeakClean), suite)
	}
	b.WriteString("\n")
}

func isoSuiteCell(r isoRecord) string {
	if !r.HasScript {
		return "native/by-construction — " + r.Note
	}
	if r.RanErr != "" {
		return "run error: " + tail(r.RanErr, 70)
	}
	return fmtCounts(r.Passed, r.Failed, r.ScriptOK)
}

// leakCell renders the leak column: PASS (clean) = "none ✓", FAIL = "LEAK ✗".
func leakCell(clean string) string {
	switch clean {
	case sigPass:
		return "none " + sigPass
	case sigFail:
		return "LEAK " + sigFail
	default:
		return sigUnknown
	}
}

func isoByFramework(recs []isoRecord, fw string) (isoRecord, bool) {
	for _, r := range recs {
		if r.Framework == fw {
			return r, true
		}
	}
	return isoRecord{}, false
}

// writeCrashTable renders the crash-recovery dimension: does the framework
// survive a hard kill -9 mid-turn and resume, and is the in-flight turn lost?
func writeCrashTable(b *strings.Builder, rep reportData) {
	if len(rep.CrashRecs) == 0 {
		return
	}
	b.WriteString("## Crash recovery — `crash_recovery` (hard `kill -9` mid-turn)\n\n")
	b.WriteString("A producer process states a fact (turn 1, committed to a real on-disk store), then\n")
	b.WriteString("is **SIGKILL**ed while a second turn's model call is in-flight. A completely fresh\n")
	b.WriteString("process then resumes the same session and must recall the turn-1 fact.\n")
	b.WriteString("**Resumed** = the fresh process recovered the session; **fact recalled** = the\n")
	b.WriteString("pre-crash fact survived; **state intact** = `state_lost==false` (the crash lost only\n")
	b.WriteString("the one truly in-flight turn, nothing committed). PASSes iff all three hold. Sourced\n")
	b.WriteString("from each adapter's `test-crash.sh` (two real OS processes + a real kill).\n\n")
	b.WriteString("> **Consistent finding: no framework here has *native* crash-recovery.** What passes\n")
	b.WriteString("> does so because it persists each committed turn to a real store (SQLite / rqlite /\n")
	b.WriteString("> on-disk file) *before* the next turn, so a fresh process can re-hydrate — and the\n")
	b.WriteString("> **in-flight turn is always lost** (that is the correct, expected outcome, not a bug).\n")
	b.WriteString("> aisotropy ships no crash harness in its adapter; its blank row is by design.\n\n")
	b.WriteString("| Framework | Resumed | Fact recalled | State intact | `crash_recovery` | Suite (test-crash.sh) |\n")
	b.WriteString("|---|:--:|:--:|:--:|:--:|---|\n")
	for _, fw := range rep.Frameworks {
		r, ok := crashByFramework(rep.CrashRecs, fw)
		if !ok {
			continue
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s |\n",
			fw, r.Resumed, r.PrecrashRecalled, r.StateLost, r.crashPass(), crashSuiteCell(r))
	}
	b.WriteString("\n")
}

func crashSuiteCell(r crashRecord) string {
	if !r.HasScript {
		return "n/a — " + r.Note
	}
	if r.RanErr != "" {
		return "run error: " + tail(r.RanErr, 70)
	}
	return fmtCounts(r.Passed, r.Failed, r.ScriptOK)
}

func crashByFramework(recs []crashRecord, fw string) (crashRecord, bool) {
	for _, r := range recs {
		if r.Framework == fw {
			return r, true
		}
	}
	return crashRecord{}, false
}

// writeObservabilityTable renders the observability CAPABILITY comparison (not a
// pass/fail gate). Two axes: the framework's native observability platform
// (documented) and the arena-measured in-process OTel emission + span_count +
// logs_structured.
func writeObservabilityTable(b *strings.Builder, rep reportData) {
	if len(rep.ObsRecords) == 0 {
		return
	}
	b.WriteString("## Observability — capability comparison (not a pass/fail gate)\n\n")
	b.WriteString("Two axes. **Native platform** is each framework's own observability suite\n")
	b.WriteString("(documented, not measured here). **In-process OTel (arena-measured)** is what the\n")
	b.WriteString("`observability` mode actually emitted when driven through a real multi-op turn with\n")
	b.WriteString("an in-memory OpenTelemetry span exporter: whether OTel spans were produced, the\n")
	b.WriteString("**span count**, and whether logs were **structured**. The arena reading is a\n")
	b.WriteString("deliberately **narrow lens** — it measures in-process span emission with an in-memory\n")
	b.WriteString("exporter and does **not** capture a framework's full native platform.\n\n")
	b.WriteString("| Framework | Native platform | In-proc OTel emission | OTel measured | Spans | Structured logs | Span names |\n")
	b.WriteString("|---|---|---|:--:|--:|:--:|---|\n")
	for _, fw := range rep.Frameworks {
		r, ok := obsByFramework(rep.ObsRecords, fw)
		if !ok {
			continue
		}
		plat := nativeObsPlatform[fw]
		measured := sigUnknown
		spans := sigUnknown
		logs := sigUnknown
		names := sigUnknown
		if r.Measured {
			if r.OtelSupported {
				measured = "native " + sigPass
			} else {
				measured = "no spans " + sigFail
			}
			spans = fmt.Sprintf("%d", r.SpanCount)
			logs = boolGlyph(r.LogsStructured)
			names = spanNamesCell(r.SpanNames)
		} else if r.Note != "" {
			measured = tail(r.Note, 40)
		} else if r.RanErr != "" {
			measured = "run error"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s |\n",
			fw, plat.Platform, plat.Emission, measured, spans, logs, names)
	}
	b.WriteString("\n")
}

func boolGlyph(v bool) string {
	if v {
		return sigPass
	}
	return sigFail
}

func obsByFramework(recs []obsRecord, fw string) (obsRecord, bool) {
	for _, r := range recs {
		if r.Framework == fw {
			return r, true
		}
	}
	return obsRecord{}, false
}

func writeBenchmarks(b *strings.Builder, rep reportData) {
	if len(rep.Benches) == 0 {
		return
	}
	b.WriteString("## Benchmarks (automatic)\n\n")
	b.WriteString("All timings are runner-measured wall clock. **Warm** = steady-state over the bench\n")
	b.WriteString("iterations (each a full adapter run including the real model round-trip). **Cold-start** =\n")
	b.WriteString("median of empty-stdin probe spawns: the adapter starts, loads env, fails to parse the empty\n")
	b.WriteString("request and exits — isolating process/container + runtime spin-up with **no** model call.\n")
	b.WriteString("The cold-start *overhead* column is cold − warm p50 of the same cell's mode (floored at 0).\n\n")

	// ---- latency table (per fw × form × mode) ----
	b.WriteString("### Latency — p50 / p95, native vs docker\n\n")
	b.WriteString("| Framework | Form | Mode | p50 (ms) | p95 (ms) | Iters | Cold-start (ms) | Cold overhead (ms) | Note |\n")
	b.WriteString("|---|---|---|---:|---:|---:|---:|---:|---|\n")
	for _, c := range rep.Benches {
		if c.Skipped && c.Mode == "*" {
			fmt.Fprintf(b, "| %s | %s | — | — | — | — | — | — | %s |\n", c.Framework, c.Form, c.Note)
			continue
		}
		if c.Skipped {
			fmt.Fprintf(b, "| %s | %s | %s | — | — | 0 | %s | — | %s |\n",
				c.Framework, c.Form, c.Mode, msOrDash(c.ColdMs), c.Note)
			continue
		}
		overhead := c.ColdMs - c.WarmP50
		if overhead < 0 {
			overhead = 0
		}
		note := c.Note
		if note == "" {
			note = "—"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %d | %d | %d | %s | %d | %s |\n",
			c.Framework, c.Form, c.Mode, c.WarmP50, c.WarmP95, c.Iters, msOrDash(c.ColdMs), overhead, note)
	}
	b.WriteString("\n")

	// ---- TTFT + peak RSS (form-level, dedup) ----
	b.WriteString("### TTFT (stream) and peak RSS\n\n")
	b.WriteString("TTFT is time-to-first-token from a `stream`-mode run. Peak RSS is the child process's\n")
	b.WriteString("`getrusage` Maxrss (native form only; a one-shot process, so read as peak-not-idle).\n\n")
	b.WriteString("| Framework | Form | TTFT (ms) | Peak RSS |\n")
	b.WriteString("|---|---|---:|---:|\n")
	seen := map[string]bool{}
	for _, c := range rep.Benches {
		if c.Skipped {
			continue
		}
		k := c.Framework + "/" + c.Form
		if seen[k] {
			continue
		}
		seen[k] = true
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", c.Framework, c.Form, msOrDash(c.TTFTMs), rssHuman(c.PeakRSSKB))
	}
	b.WriteString("\n")

	// ---- docker footprint (per fw, docker form) ----
	anyDocker := false
	for _, c := range rep.Benches {
		if c.Form == "docker" {
			anyDocker = true
			break
		}
	}
	if anyDocker {
		b.WriteString("### Docker footprint\n\n")
		b.WriteString("Image size via `docker image inspect`. Build time is recorded only when the image was\n")
		b.WriteString("built during this run (blank = image was already present, not rebuilt).\n\n")
		b.WriteString("| Framework | Image size | Build time (ms) | Note |\n")
		b.WriteString("|---|---:|---:|---|\n")
		fseen := map[string]bool{}
		for _, c := range rep.Benches {
			if c.Form != "docker" || fseen[c.Framework] {
				continue
			}
			fseen[c.Framework] = true
			if c.Skipped {
				fmt.Fprintf(b, "| %s | — | — | %s |\n", c.Framework, c.Note)
				continue
			}
			build := "—"
			if c.BuildMs > 0 {
				build = fmt.Sprintf("%d", c.BuildMs)
			}
			size := c.ImageSize
			if size == "" {
				size = "n/a"
			}
			fmt.Fprintf(b, "| %s | %s | %s | — |\n", c.Framework, size, build)
		}
		b.WriteString("\n")
	}
}

func writeTokenTable(b *strings.Builder, rep reportData, aggs map[string]*modeAgg, get func(fw, mode string) *modeAgg) {
	b.WriteString("## Measured token spend — per framework × per mode\n\n")
	b.WriteString("Provider-reported `usage` only, summed across every internal model call a work item made\n")
	b.WriteString("(memory sums its persist+recall invocations — its honest per-turn re-hydration cost).\n")
	b.WriteString("Runs where usage was unavailable report `-1` and are excluded from the sums.\n\n")
	b.WriteString("| Framework | Mode | Total input | Total output | Total | Avg in/task | Avg out/task | Runs w/ usage |\n")
	b.WriteString("|---|---|---:|---:|---:|---:|---:|---:|\n")
	for _, fw := range rep.Frameworks {
		for _, mode := range rep.Modes {
			a := get(fw, mode)
			if a.tokN == 0 {
				continue
			}
			fmt.Fprintf(b, "| %s | %s | %d | %d | %d | %s | %s | %d |\n",
				fw, mode, a.inSum, a.outSum, a.inSum+a.outSum,
				fmt1(avg(a.inSum, a.tokN)), fmt1(avg(a.outSum, a.tokN)), a.tokN)
		}
	}
	b.WriteString("\n")
}

func writePerItemDetail(b *strings.Builder, records []record) {
	if len(records) == 0 {
		return
	}
	b.WriteString("## Per-item detail\n\n")
	b.WriteString("**Det** is the PRIMARY deterministic pass/fail (`arenas/live/runner/scoring`) with its\n")
	b.WriteString("one-line reason; **Corr/Help/Faith** are the SECONDARY, opt-in LLM-judge axes (blank\n")
	b.WriteString("unless `-llm-judge` was passed this run).\n\n")
	b.WriteString("| Framework | Mode | Item | Kind | Latency (ms) | In tok | Out tok | Det | Det detail | Corr | Help | Faith | Signal | Error |\n")
	b.WriteString("|---|---|---|---|---:|---:|---:|:--:|---|---:|---:|---:|---|---|\n")
	for _, r := range records {
		errCell := "—"
		if r.RunErr != "" {
			errCell = "run: " + tail(r.RunErr, 70)
		} else if r.Out.Error != "" {
			errCell = "adapter: " + tail(r.Out.Error, 70)
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
			r.Framework, r.Mode, r.ID, r.Kind, r.WallMs,
			tokCell(r.SumIn, r.HasTok), tokCell(r.SumOut, r.HasTok),
			detGlyph(r.Det), tail(r.Det.Detail, 60),
			scoreCell(r.Correctness), scoreCell(r.Helpfulness), scoreCell(r.Faithfulness),
			itemSignal(r), errCell)
	}
	b.WriteString("\n")
}

// detGlyph renders the per-item primary deterministic pass/fail glyph.
func detGlyph(sc scoring.Score) string {
	if sc.Detail == "" {
		return sigUnknown
	}
	if sc.Pass {
		return sigPass
	}
	return sigFail
}

func itemSignal(r record) string {
	switch r.Kind {
	case "rag_grounded":
		if r.RetrievalHit {
			return "hit@1 ✓"
		}
		return "hit@1 ✗"
	case "rag_trap":
		if r.TrapRefused {
			return "refused ✓"
		}
		return "invented ✗"
	case "tools":
		switch {
		case r.ToolExecuted && r.AnswerCorrect:
			return "exec+correct ✓"
		case r.ToolExecuted:
			return "exec, wrong #"
		case r.AnswerCorrect:
			return "no-exec, right #"
		default:
			return "no tool ✗"
		}
	case "structured":
		if r.StructuredOK {
			return "valid JSON ✓"
		}
		return "no structured ✗"
	case "stream":
		return fmt.Sprintf("ttft %dms", r.TTFTMs)
	default:
		return "—"
	}
}

