func fmt1(v float64) string {
	if math.IsNaN(v) {
		return "—"
	}
	return fmt.Sprintf("%.1f", v)
}

func fmtLatency(sum int64, n int) string {
	if n == 0 {
		return "—"
	}
	return fmt.Sprintf("%d", sum/int64(n))
}

func msOrDash(v int64) string {
	if v <= 0 {
		return "—"
	}
	return fmt.Sprintf("%d", v)
}

func rssHuman(kb int64) string {
	if kb <= 0 {
		return "—"
	}
	return humanizeBytes(kb * 1024)
}

func tokCell(v int, has bool) string {
	if !has || v < 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d", v)
}

func scoreCell(v int) string {
	if v == 0 {
		return "—"
	}
	return fmt.Sprintf("%d", v)
}

func dimsOrAll(d []string) []string {
	if len(d) == 0 {
		return []string{"none"}
	}
	return d
}

func avg(sum, count int) float64 {
	if count == 0 {
		return math.NaN()
	}
	return float64(sum) / float64(count)
}

// avg2 is avg for a float64 sum (the deterministic score's Value, which is
// itself a float in [0,1]).
func avg2(sum float64, count int) float64 {
	if count == 0 {
		return math.NaN()
	}
	return sum / float64(count)
}
