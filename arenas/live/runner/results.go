// reportData is everything writeResults needs to render RESULTS.md.
type reportData struct {
	Model      string
	Frameworks []string
	Modes      []string
	Dimensions []string
	BenchModes []string
	Forms      []string
	BenchIters int
	ColdProbes int
	JudgeOn    bool
	Records    []record
	Benches    []benchCell
	IsoRecords []isoRecord
	CrashRecs  []crashRecord
	ObsRecords []obsRecord
	ModelCalls int
}

// per (framework, mode) correctness aggregate.
type modeAgg struct {
	runs, errors int

	corrSum, helpSum, faithSum, judged int

	latSum int64
	latN   int
	inSum  int
	outSum int
	tokN   int

	// rag
	groundedN, retrievalHits int
	trapN, trapRefused       int

	// tools
	toolN, toolExec, toolCorrect int

	// structured
	structN, structOK int

	// stream
	ttftSum int64
	ttftN   int
}

func writeResults(path string, rep reportData) error {
	// aggregate correctness records per (framework, mode)
	aggs := map[string]*modeAgg{}
	key := func(fw, mode string) string { return fw + "\x00" + mode }
	get := func(fw, mode string) *modeAgg {
		k := key(fw, mode)
		a := aggs[k]
		if a == nil {
			a = &modeAgg{}
			aggs[k] = a
		}
		return a
	}
	for _, r := range rep.Records {
		a := get(r.Framework, r.Mode)
		a.runs++
		if r.failed() {
			a.errors++
			continue
		}
		a.latSum += r.WallMs
		a.latN++
		if r.HasTok {
			a.inSum += r.SumIn
			a.outSum += r.SumOut
			a.tokN++
		}
		if r.Correctness > 0 {
			a.corrSum += r.Correctness
			a.helpSum += r.Helpfulness
			a.faithSum += r.Faithfulness
			a.judged++
		}
		switch r.Kind {
		case "rag_grounded":
			a.groundedN++
			if r.RetrievalHit {
				a.retrievalHits++
			}
		case "rag_trap":
			a.trapN++
			if r.TrapRefused {
				a.trapRefused++
			}
		case "tools":
			a.toolN++
			if r.ToolExecuted {
				a.toolExec++
			}
			if r.AnswerCorrect {
				a.toolCorrect++
			}
		case "structured":
			a.structN++
			if r.StructuredOK {
				a.structOK++
			}
		case "stream":
			if r.TTFTMs > 0 {
				a.ttftSum += r.TTFTMs
				a.ttftN++
			}
		}
	}

	var b strings.Builder
	writeHeader(&b, rep)
	writeQualityTable(&b, rep, aggs, get)
	writeScopedIsolationTable(&b, rep)
	writeCrashTable(&b, rep)
	writeObservabilityTable(&b, rep)
	writeBenchmarks(&b, rep)
	writeTokenTable(&b, rep, aggs, get)
	writePerItemDetail(&b, rep.Records)
	writeNotes(&b, rep)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func writeHeader(b *strings.Builder, rep reportData) {
	model := rep.Model
	fmt.Fprintf(b, `---
type: Results
title: "Live arena results — %s held constant, frameworks × modes benchmarked"
description: Generated by arenas/live/runner. Every framework calls the REAL %s, so measured differences are the framework's. Two passes — a per-mode correctness/quality pass (LLM-judged) and an automatic benchmark pass (latency p50/p95 native vs docker, cold-start, TTFT, tokens, footprint). Contrast with arenas/BENCHMARKS.md, which holds the model constant as a zero-latency stub to isolate overhead and states its quality numbers are documented-not-executed.
tags: [arenas, live, results, agnes, quality, latency, cold-start, ttft, tokens, footprint, tool-calling, memory, rag]
---

# Live arena results — modes × benchmarks

`, model, model)

	fmt.Fprintf(b, "> **Run:** %s • **Model (held constant):** `%s` • **Modes:** %s • **Frameworks:** %d • **Execution forms:** %s\n",
		time.Now().UTC().Format("2006-01-02 15:04 MST"), model,
		strings.Join(rep.Modes, ", "), len(rep.Frameworks), strings.Join(rep.Forms, ", "))
	fmt.Fprintf(b, "> **Billable model round-trips this run:** %d • **Bench modes:** %s • **Bench iters:** %d • **Cold probes:** %d (empty-stdin, 0 model calls)\n",
		rep.ModelCalls, strings.Join(rep.BenchModes, ", "), rep.BenchIters, rep.ColdProbes)
	if len(rep.Dimensions) > 0 {
		fmt.Fprintf(b, "> **New dimensions:** %s (scoped-memory & isolation, crash recovery, observability capability)\n", strings.Join(rep.Dimensions, ", "))
	}
	b.WriteString("\n")

	b.WriteString("> **The model is real and identical for every row.** Because every framework calls the\n")
	b.WriteString("> same `" + model + "` with the same credentials, a difference in a column is a property of\n")
	b.WriteString("> the **framework**, not the model. This is the executable counterpart to `arenas/BENCHMARKS.md`\n")
	b.WriteString("> (which holds the model constant as a keyless stub to measure framework *overhead*, and is\n")
	b.WriteString("> explicit that its quality table is *documented, not executed*).\n\n")

	if rep.JudgeOn {
		b.WriteString("> **⚠️ Self-judge caveat.** Correctness / helpfulness / faithfulness are scored by an\n")
		b.WriteString("> **LLM-as-judge on the same model family as the contestants** (`" + model + "` judging `" + model + "`\n")
		b.WriteString("> outputs). A model tends to rate its own family generously and cannot catch errors it would\n")
		b.WriteString("> itself make, so these scores are a **relative, directional** signal — **not** an absolute\n")
		b.WriteString("> measure of truth. The judge runs over agnes's Chat Completions endpoint (`/chat/completions`);\n")
		b.WriteString("> agnes does **not** support the Responses API. Latency, cold-start, TTFT, tokens and footprint\n")
		b.WriteString("> are objective measurements and carry no such caveat.\n\n")
	} else {
		b.WriteString("> _Judge pass skipped (`-skip-judge`): quality columns are blank; latency, tokens, cold-start,\n")
		b.WriteString("> TTFT, footprint and the objective per-mode signals (retrieval hit@1, trap-refusal, tool\n")
		b.WriteString("> execution, structured-validity) are still real measurements._\n\n")
	}
}

func writeQualityTable(b *strings.Builder, rep reportData, aggs map[string]*modeAgg, get func(fw, mode string) *modeAgg) {
	b.WriteString("## Correctness / quality — per framework × per mode\n\n")
	b.WriteString("Quality axes are 1–5 (LLM-judged, higher is better), averaged over the judged tasks of\n")
	b.WriteString("that mode. The **Mode signal** column is the objective, un-judged metric for the mode\n")
	b.WriteString("(rag: retrieval hit@1 on the gold doc + trap-refusal; tools: real tool execution + numeric\n")
	b.WriteString("correctness; structured: schema-valid JSON; stream: mean TTFT). Latency is end-to-end\n")
	b.WriteString("wall-clock (native, correctness pass) including the real model round-trip(s).\n\n")
	b.WriteString("| Framework | Mode | Correctness | Helpfulness | Faithfulness | Mode signal | Avg latency (ms) | Runs | Err |\n")
	b.WriteString("|---|---|---:|---:|---:|---|---:|---:|---:|\n")

	for _, fw := range rep.Frameworks {
		for _, mode := range rep.Modes {
			a := get(fw, mode)
			if a.runs == 0 {
				continue
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s | %d | %d |\n",
				fw, mode,
				fmt1(avg(a.corrSum, a.judged)),
				fmt1(avg(a.helpSum, a.judged)),
				fmt1(avg(a.faithSum, a.judged)),
				modeSignal(mode, a),
				fmtLatency(a.latSum, a.latN),
				a.runs, a.errors,
			)
		}
	}
	b.WriteString("\n")
}

func modeSignal(mode string, a *modeAgg) string {
	switch mode {
	case "rag":
		parts := []string{}
		if a.groundedN > 0 {
			parts = append(parts, fmt.Sprintf("hit@1 %d/%d", a.retrievalHits, a.groundedN))
		}
		if a.trapN > 0 {
			parts = append(parts, fmt.Sprintf("trap-refuse %d/%d", a.trapRefused, a.trapN))
		}
		if len(parts) == 0 {
			return "—"
		}
		return strings.Join(parts, ", ")
	case "tools":
		if a.toolN == 0 {
			return "—"
		}
		return fmt.Sprintf("exec %d/%d, correct %d/%d", a.toolExec, a.toolN, a.toolCorrect, a.toolN)
	case "structured":
		if a.structN == 0 {
			return "—"
		}
		return fmt.Sprintf("valid %d/%d", a.structOK, a.structN)
	case "stream":
		if a.ttftN == 0 {
			return "—"
		}
		return fmt.Sprintf("TTFT %dms (n=%d)", a.ttftSum/int64(a.ttftN), a.ttftN)
	case "memory":
		return "recall (judged)"
	default:
		return "—"
	}
}

// writeScopedIsolationTable renders the multi-tenant scoped-memory & isolation
// dimension: per framework, same-scope hit / cross-tenant miss / leak-detected,
// sourced from each adapter's authoritative test-isolation.sh.
func writeScopedIsolationTable(b *strings.Builder, rep reportData) {
	if len(rep.IsoRecords) == 0 {
		return
	}
	b.WriteString("## Scoped memory & tenant isolation — `memory_scoped` + `isolation_leak`\n\n")
	b.WriteString("Multi-tenant scoped memory: a fact written under a compound scope\n")
	b.WriteString("`(tenant_id, user_id, product_id)` must be recalled in that exact scope\n")
	b.WriteString("(**same-scope hit**), must NOT be recalled under a different `tenant_id`\n")
	b.WriteString("(**cross-tenant miss**), and a secret seeded by tenant A must never surface when\n")
	b.WriteString("probed as tenant B (**leak? = none**). `memory_scoped` PASSes iff same-scope hit\n")
	b.WriteString("**and** cross-tenant miss; `isolation_leak` PASSes iff no leak. Each row is sourced\n")
	b.WriteString("from that adapter's own `test-isolation.sh` (real agnes recall/probe calls), the\n")
	b.WriteString("authoritative deterministic signal for its specific contract.\n\n")
	b.WriteString("> **Native vs hand-rolled (honest caveat).** aisotropy enforces tenant isolation\n")
	b.WriteString("> **by construction** in the core runtime — `tenant_id` travels only via\n")
	b.WriteString("> `context.Context` and Qdrant does payload-filtered HNSW scans (a constitutional\n")
	b.WriteString("> gate), so it ships **no** hand-rolled arena isolation harness. Every other\n")
	b.WriteString("> framework here has **no native multi-tenant memory primitive** and hand-rolls a\n")
	b.WriteString("> compound scope key over its store; this table exercises exactly that hand-rolled\n")
	b.WriteString("> key. A blank aisotropy row is therefore *by design*, not a failure.\n\n")
	b.WriteString("| Framework | Same-scope hit | Cross-tenant miss | `memory_scoped` | Leak? (none=pass) | Suite (test-isolation.sh) |\n")
	b.WriteString("|---|:--:|:--:|:--:|:--:|---|\n")
	for _, fw := range rep.Frameworks {
		r, ok := isoByFramework(rep.IsoRecords, fw)
		if !ok {
			continue
		}
		suite := isoSuiteCell(r)
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s |\n",
			fw, r.SameScopeHit, r.CrossTenantMiss, r.scopedPass(), leakCell(r.LeakClean), suite)
	}
	b.WriteString("\n")
}

func isoSuiteCell(r isoRecord) string {
	if !r.HasScript {
		return "native/by-construction — " + r.Note
	}
	if r.RanErr != "" {
		return "run error: " + tail(r.RanErr, 70)
	}
	return fmtCounts(r.Passed, r.Failed, r.ScriptOK)
}

// leakCell renders the leak column: PASS (clean) = "none ✓", FAIL = "LEAK ✗".
func leakCell(clean string) string {
	switch clean {
	case sigPass:
		return "none " + sigPass
	case sigFail:
		return "LEAK " + sigFail
	default:
		return sigUnknown
	}
}

func isoByFramework(recs []isoRecord, fw string) (isoRecord, bool) {
	for _, r := range recs {
		if r.Framework == fw {
			return r, true
		}
	}
	return isoRecord{}, false
}

// writeCrashTable renders the crash-recovery dimension: does the framework
// survive a hard kill -9 mid-turn and resume, and is the in-flight turn lost?
func writeCrashTable(b *strings.Builder, rep reportData) {
	if len(rep.CrashRecs) == 0 {
		return
	}
	b.WriteString("## Crash recovery — `crash_recovery` (hard `kill -9` mid-turn)\n\n")
	b.WriteString("A producer process states a fact (turn 1, committed to a real on-disk store), then\n")
	b.WriteString("is **SIGKILL**ed while a second turn's model call is in-flight. A completely fresh\n")
	b.WriteString("process then resumes the same session and must recall the turn-1 fact.\n")
	b.WriteString("**Resumed** = the fresh process recovered the session; **fact recalled** = the\n")
	b.WriteString("pre-crash fact survived; **state intact** = `state_lost==false` (the crash lost only\n")
	b.WriteString("the one truly in-flight turn, nothing committed). PASSes iff all three hold. Sourced\n")
	b.WriteString("from each adapter's `test-crash.sh` (two real OS processes + a real kill).\n\n")
	b.WriteString("> **Consistent finding: no framework here has *native* crash-recovery.** What passes\n")
	b.WriteString("> does so because it persists each committed turn to a real store (SQLite / rqlite /\n")
	b.WriteString("> on-disk file) *before* the next turn, so a fresh process can re-hydrate — and the\n")
	b.WriteString("> **in-flight turn is always lost** (that is the correct, expected outcome, not a bug).\n")
	b.WriteString("> aisotropy ships no crash harness in its adapter; its blank row is by design.\n\n")
	b.WriteString("| Framework | Resumed | Fact recalled | State intact | `crash_recovery` | Suite (test-crash.sh) |\n")
	b.WriteString("|---|:--:|:--:|:--:|:--:|---|\n")
	for _, fw := range rep.Frameworks {
		r, ok := crashByFramework(rep.CrashRecs, fw)
		if !ok {
			continue
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s |\n",
			fw, r.Resumed, r.PrecrashRecalled, r.StateLost, r.crashPass(), crashSuiteCell(r))
	}
	b.WriteString("\n")
}

